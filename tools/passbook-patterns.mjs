// Store a passbook printer's dot patterns, once per printer type.
//
//   node tools/passbook-patterns.mjs <page.pgm> <answer.json> <out.js>
//
// <page.pgm>: ONE scanned passbook page as grey (ink dark: the darkest of red,
// green, blue), <answer.json>: what that page says, as a person read it -
// [[date, amount, balance], ...] one entry per printed line. Both are private
// and stay outside this repository; only the patterns are written: each is a
// single symbol's dots, with nothing that says which line or figure it came from.
// Up to KEEP varied patterns per symbol are kept, so reading stays fast.
import fs from 'node:fs';
import { cutPage, patternFromBox, encodePattern, CW, CH } from '../src/passbook/reader.js';

const [pgmPath, answerPath, outPath] = process.argv.slice(2);
if (!outPath) { console.error('usage: node tools/passbook-patterns.mjs <page.pgm> <answer.json> <out.js>'); process.exit(2); }
const KEEP = 12;

const buf = fs.readFileSync(pgmPath);
const head = buf.toString('latin1', 0, 40).match(/^P5\s+(\d+)\s+(\d+)\s+255\s/);
const img = { w: +head[1], h: +head[2], px: new Uint8Array(buf.subarray(head[0].length)) };
const answer = JSON.parse(fs.readFileSync(answerPath, 'utf8'));

// Krungthai passbook, measured on the scan at 200 dpi: box width / line height.
const printer = { inkBelow: 150, lineHeight: 21, ratio: 10.32 / 21 };
const lines = cutPage(img, printer);
if (lines.length !== answer.length) console.warn(`warning: ${lines.length} lines found, answer has ${answer.length}`);

// Label by column position (never "the second group from the right": a missing
// staff id would shift that onto the amount). Positions measured on page 1.
const span = g => [g[0].x0, g[g.length - 1].x1];
const labelled = [];
let used = 0, skipped = 0;
lines.forEach((line, i) => {
  const [date, amount, balance] = answer[i] ?? [];
  const take = (g, text) => {
    if (!g || !text || g.length !== text.length) { skipped++; return; }
    g.forEach((box, k) => labelled.push(patternFromBox(text[k], box)));
    used++;
  };
  take(line.groups.find(g => Math.abs(span(g)[0] - 679) < 25), date);
  take(line.groups.find(g => Math.abs(span(g)[1] - 1526) < 25), balance);
  if (amount) take(line.groups.find(g => span(g)[1] > 1050 && span(g)[1] < 1320), amount);
});

// Keep the most different examples of each symbol (farthest-first).
const corr = (a, b) => {
  let ab = 0; for (let i = 0; i < a.f.length; i++) ab += a.f[i] * b.f[i];
  return (ab - a.sa * b.sa / a.f.length) / Math.sqrt(a.va * b.va);
};
const stored = {};
for (const ch of [...new Set(labelled.map(p => p.ch))].sort()) {
  const all = labelled.filter(p => p.ch === ch && p.va > 0);
  const keep = [all[0]];
  while (keep.length < Math.min(KEEP, all.length)) {
    let far = null;
    for (const p of all) {
      if (keep.includes(p)) continue;
      const near = Math.max(...keep.map(k => corr(p, k)));
      if (!far || near < far.near) far = { p, near };
    }
    keep.push(far.p);
  }
  stored[ch] = keep.map(encodePattern);
}
const counts = Object.entries(stored).map(([ch, l]) => `${ch}:${l.length}`).join(' ');
console.log(`${used} figures labelled, ${skipped} skipped; kept ${counts}`);

const body = `// Generated by tools/passbook-patterns.mjs from ONE page of a Krungthai
// passbook scan (200 dpi). Each entry is one symbol's dots (${CW}x${CH} grey,
// base64) - no figure, line or account can be rebuilt from them.
export const STORED = ${JSON.stringify(stored, null, 0).replace(/\],/g, '],\n  ')};
`;
fs.writeFileSync(outPath, body);
